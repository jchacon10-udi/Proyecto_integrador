CREATE TABLE GASTO_DIARIO (
 ID_GASTO NUMBER(19,0) NOT NULL,
 ID_JORNADA NUMBER(10,0) NOT NULL,
 NUMERO_ORDEN NUMBER(5,0) NOT NULL,
 DESCRIPCION VARCHAR2(180) NOT NULL,
 CANTIDAD NUMBER(10,2) NOT NULL,
 ID_UNIDAD NUMBER(5,0),
 TIPO_ITEM VARCHAR2(8) NOT NULL,
 EQUIVALENCIA_G_CC NUMBER(12,2),
 ID_FORMA NUMBER(5,0) NOT NULL,
 ID_LUGAR NUMBER(5,0),
 VALOR_PAGADO_ESTIMADO NUMBER(14,2) NOT NULL,
 ID_FRECUENCIA NUMBER(5,0),
 TIPO_GASTO VARCHAR2(2) NOT NULL,
 CONSTRAINT PK_GASTO_DIARIO PRIMARY KEY (ID_GASTO),
 CONSTRAINT FK_GD_JORNADA FOREIGN KEY (ID_JORNADA) REFERENCES JORNADA_DIARIA(ID_JORNADA),
 CONSTRAINT FK_GD_UNIDAD FOREIGN KEY (ID_UNIDAD) REFERENCES UNIDAD_MEDIDA(ID_UNIDAD),
 CONSTRAINT FK_GD_FORMA FOREIGN KEY (ID_FORMA) REFERENCES FORMA_ADQUISICION(ID_FORMA),
 CONSTRAINT FK_GD_LUGAR FOREIGN KEY (ID_LUGAR) REFERENCES LUGAR_COMPRA(ID_LUGAR),
 CONSTRAINT FK_GD_FRECUENCIA FOREIGN KEY (ID_FRECUENCIA) REFERENCES FRECUENCIA_COMPRA(ID_FRECUENCIA),
 CONSTRAINT UQ_GD_JORNADA_ORDEN UNIQUE (ID_JORNADA, NUMERO_ORDEN),
 CONSTRAINT CK_GD_CANT CHECK (CANTIDAD > 0),
 CONSTRAINT CK_GD_EQ CHECK (EQUIVALENCIA_G_CC >= 0),
 CONSTRAINT CK_GD_VAL CHECK (VALOR_PAGADO_ESTIMADO >= 0),
 CONSTRAINT CK_GD_TIPO CHECK (TIPO_GASTO IN ('1','2','NA')),
 CONSTRAINT CK_GD_ITEM CHECK (TIPO_ITEM IN ('BIEN','SERVICIO')),
 CONSTRAINT CK_GD_UNIDAD CHECK (TIPO_ITEM='SERVICIO' OR ID_UNIDAD IS NOT NULL)
);

CREATE TABLE COMIDA_FUERA (
 ID_COMIDA NUMBER(19,0) NOT NULL,
 ID_JORNADA NUMBER(10,0) NOT NULL,
 NUMERO_ORDEN NUMBER(5,0) NOT NULL,
 DESCRIPCION VARCHAR2(180) NOT NULL,
 TIPO_COMIDA VARCHAR2(20) NOT NULL,
 CANTIDAD NUMBER(10,2) NOT NULL,
 ID_FORMA NUMBER(5,0) NOT NULL,
 ID_LUGAR NUMBER(5,0),
 VALOR_PAGADO_ESTIMADO NUMBER(14,2) NOT NULL,
 ID_FRECUENCIA NUMBER(5,0),
 TIPO_GASTO CHAR(1) NOT NULL,
 DOMICILIO NUMBER(1,0) NOT NULL,
 CONSTRAINT PK_COMIDA_FUERA PRIMARY KEY (ID_COMIDA),
 CONSTRAINT FK_CF_JORNADA FOREIGN KEY (ID_JORNADA) REFERENCES JORNADA_DIARIA(ID_JORNADA),
 CONSTRAINT FK_CF_FORMA FOREIGN KEY (ID_FORMA) REFERENCES FORMA_ADQUISICION(ID_FORMA),
 CONSTRAINT FK_CF_LUGAR FOREIGN KEY (ID_LUGAR) REFERENCES LUGAR_COMPRA(ID_LUGAR),
 CONSTRAINT FK_CF_FRECUENCIA FOREIGN KEY (ID_FRECUENCIA) REFERENCES FRECUENCIA_COMPRA(ID_FRECUENCIA),
 CONSTRAINT UQ_CF_JORNADA_ORDEN UNIQUE (ID_JORNADA, NUMERO_ORDEN),
 CONSTRAINT CK_CF_CANT CHECK (CANTIDAD > 0),
 CONSTRAINT CK_CF_VAL CHECK (VALOR_PAGADO_ESTIMADO >= 0),
 CONSTRAINT CK_CF_TIPO CHECK (TIPO_GASTO IN ('1','2')),
 CONSTRAINT CK_CF_DOM CHECK (DOMICILIO IN (0,1))
);

CREATE TABLE CIERRE_CUADERNILLO (
 ID_CIERRE NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 GASTO_EVENTO_ESPECIAL NUMBER(1,0) NOT NULL,
 FORMA_PAGO_PRINCIPAL VARCHAR2(30) NOT NULL,
 OTRA_FORMA_PAGO VARCHAR2(80),
 OBSERVACIONES VARCHAR2(500),
 ESTADO_REVISION VARCHAR2(20) NOT NULL,
 ID_SUPERVISOR NUMBER(10,0),
 FECHA_REVISION TIMESTAMP,
 CONSTRAINT PK_CIERRE_CUADERNILLO PRIMARY KEY (ID_CIERRE),
 CONSTRAINT UQ_CC_HOGAR UNIQUE (ID_HOGAR),
 CONSTRAINT FK_CC_HOGAR FOREIGN KEY (ID_HOGAR) REFERENCES HOGAR(ID_HOGAR),
 CONSTRAINT FK_CC_SUP FOREIGN KEY (ID_SUPERVISOR) REFERENCES USUARIO(ID_USUARIO),
 CONSTRAINT CK_CC_EVENTO CHECK (GASTO_EVENTO_ESPECIAL IN (0,1))
);

CREATE SEQUENCE SEQ_ROL START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE OR REPLACE TRIGGER BI_ROL
BEFORE INSERT ON ROL
FOR EACH ROW
BEGIN
 IF :NEW.ID_ROL IS NULL THEN
  SELECT SEQ_ROL.NEXTVAL INTO :NEW.ID_ROL FROM DUAL;
 END IF;
END;
/

