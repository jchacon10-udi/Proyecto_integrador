-- RECONSTRUCCION DESDE DICCIONARIO DE DATOS (PRIMER AVANCE / REV2).
-- NO ES EL SQL ORIGINAL NI HA SIDO EJECUTADO EN ORACLE 10g.
-- USO: despliegue de una BASE VACIA para pruebas, previa revision.
-- NO EJECUTAR en esquema con tablas existentes. No contiene DROP.
-- 17 tablas originales, sin REVISION_CRITICA ni HALLAZGO_CRITICA.
-- Adaptaciones sintacticas Oracle 10g: VARCHAR2, NUMBER, DATE/TIMESTAMP;
-- BOOLEAN se representa con NUMBER(1) CHECK(0,1); TIME con DATE.
-- Continuacion: D usa 1/2/NA expreso, sin inferir NA por forma de adquisicion.
-- D1 conserva 1/2. ID_UNIDAD opcional para SERVICIO; BIEN exige unidad.
-- TIPO_ITEM es clasificacion controlada, no inferida de DESCRIPCION.
-- DIA_ENCUESTA de JORNADA es obligatorio 1..14; fecha/periodo en negocio.
-- Las columnas de HORA_* representadas como DATE almacenan fecha y hora,
-- debe validarse su coherencia con FECHA en la capa de aplicacion.
-- ID primarios por secuencias/triggers son propuesta de reconstruccion,
-- pues el Word no proporciona secuencias ni triggers reales.

CREATE TABLE ROL (
 ID_ROL NUMBER(5,0) NOT NULL,
 NOMBRE VARCHAR2(30) NOT NULL,
 CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL),
 CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIO (
 ID_USUARIO NUMBER(10,0) NOT NULL,
 ID_ROL NUMBER(5,0) NOT NULL,
 NOMBRE VARCHAR2(100) NOT NULL,
 CORREO VARCHAR2(120) NOT NULL,
 CLAVE_HASH VARCHAR2(255) NOT NULL,
 ESTADO VARCHAR2(15) NOT NULL,
 CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
 CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO),
 CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL(ID_ROL)
);

CREATE TABLE HOGAR (
 ID_HOGAR NUMBER(10,0) NOT NULL,
 CODIGO_OPERATIVO VARCHAR2(30) NOT NULL,
 REGION VARCHAR2(5) NOT NULL,
 DEPARTAMENTO VARCHAR2(5) NOT NULL,
 MUNICIPIO VARCHAR2(8) NOT NULL,
 CLASE VARCHAR2(5) NOT NULL,
 SECTOR VARCHAR2(8),
 SECCION VARCHAR2(8),
 MANZANA VARCHAR2(8),
 SEGMENTO VARCHAR2(8),
 CICLO VARCHAR2(5),
 EDIFICACION_NUMERO VARCHAR2(8),
 VIVIENDA_NUMERO VARCHAR2(8),
 TOTAL_HOGARES_VIVIENDA NUMBER(5,0) NOT NULL,
 TOTAL_PERSONAS NUMBER(5,0) NOT NULL,
 BARRIO_VEREDA VARCHAR2(120),
 DIRECCION VARCHAR2(180) NOT NULL,
 TELEFONO VARCHAR2(30),
 RESULTADO VARCHAR2(5),
 ESTADO VARCHAR2(20) NOT NULL,
 CONSTRAINT PK_HOGAR PRIMARY KEY (ID_HOGAR),
 CONSTRAINT UQ_HOGAR_CODIGO UNIQUE (CODIGO_OPERATIVO),
 CONSTRAINT CK_HOGAR_TOT_HOG CHECK (TOTAL_HOGARES_VIVIENDA >= 1),
 CONSTRAINT CK_HOGAR_TOT_PER CHECK (TOTAL_PERSONAS >= 1)
);

CREATE TABLE ASIGNACION_HOGAR (
 ID_ASIGNACION NUMBER(10,0) NOT NULL,
 ID_USUARIO NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 FECHA_ASIGNACION DATE NOT NULL,
 ESTADO VARCHAR2(15) NOT NULL,
 CONSTRAINT PK_ASIGNACION_HOGAR PRIMARY KEY (ID_ASIGNACION),
 CONSTRAINT FK_AH_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
 CONSTRAINT FK_AH_HOGAR FOREIGN KEY (ID_HOGAR) REFERENCES HOGAR(ID_HOGAR)
);

CREATE TABLE PERIODO_RECOLECCION (
 ID_PERIODO NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 FECHA_INICIO DATE NOT NULL,
 FECHA_FIN DATE NOT NULL,
 ESTADO VARCHAR2(15) NOT NULL,
 CONSTRAINT PK_PERIODO_RECOLECCION PRIMARY KEY (ID_PERIODO),
 CONSTRAINT UQ_PR_HOGAR UNIQUE (ID_HOGAR),
 CONSTRAINT FK_PR_HOGAR FOREIGN KEY (ID_HOGAR) REFERENCES HOGAR(ID_HOGAR),
 CONSTRAINT CK_PR_RANGO CHECK (TRUNC(FECHA_FIN) = TRUNC(FECHA_INICIO) + 13)
);

CREATE TABLE VISITA (
 ID_VISITA NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 NUMERO_VISITA NUMBER(2,0) NOT NULL,
 FECHA DATE NOT NULL,
 HORA_INICIO DATE,
 HORA_FIN DATE,
 RESULTADO_ENTREVISTA VARCHAR2(5) NOT NULL,
 PENDIENTES VARCHAR2(300),
 PROXIMA_FECHA DATE,
 PROXIMA_HORA DATE,
 CONSTRAINT PK_VISITA PRIMARY KEY (ID_VISITA),
 CONSTRAINT FK_VISITA_HOGAR FOREIGN KEY (ID_HOGAR) REFERENCES HOGAR(ID_HOGAR),
 CONSTRAINT UQ_VISITA_NUM UNIQUE (ID_HOGAR, NUMERO_VISITA),
 CONSTRAINT CK_VISITA_NUM CHECK (NUMERO_VISITA BETWEEN 1 AND 14)
);

CREATE TABLE GRUPO_ALIMENTO (
 ID_GRUPO NUMBER(5,0) NOT NULL,
 CODIGO VARCHAR2(3) NOT NULL,
 NOMBRE VARCHAR2(180) NOT NULL,
 CONSTRAINT PK_GRUPO_ALIMENTO PRIMARY KEY (ID_GRUPO),
 CONSTRAINT UQ_GA_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE FRECUENCIA_COMPRA (
