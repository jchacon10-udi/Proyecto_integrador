CREATE TABLE CARACTERISTICA_GASTO (
 ID_CARACTERISTICA NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 ID_GRUPO NUMBER(5,0) NOT NULL,
 ID_FRECUENCIA NUMBER(5,0) NOT NULL,
 VALOR_ULTIMA_COMPRA NUMBER(14,2),
 COMPRARA_14_DIAS NUMBER(1,0),
 CONSTRAINT PK_CARACTERISTICA_GASTO PRIMARY KEY (ID_CARACTERISTICA),
 CONSTRAINT FK_CG_HOGAR FOREIGN KEY (ID_HOGAR) REFERENCES HOGAR(ID_HOGAR),
 CONSTRAINT FK_CG_GRUPO FOREIGN KEY (ID_GRUPO) REFERENCES GRUPO_ALIMENTO(ID_GRUPO),
 CONSTRAINT FK_CG_FRECUENCIA FOREIGN KEY (ID_FRECUENCIA) REFERENCES FRECUENCIA_COMPRA(ID_FRECUENCIA),
 CONSTRAINT UQ_CG_HOGAR_GRUPO UNIQUE (ID_HOGAR, ID_GRUPO),
 CONSTRAINT CK_CG_VAL CHECK (VALOR_ULTIMA_COMPRA >= 0),
 CONSTRAINT CK_CG_COMPRA CHECK (COMPRARA_14_DIAS IN (0,1))
);

CREATE TABLE RESUMEN_MERCADO (
 ID_RESUMEN NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 CODIGO_MERCADO VARCHAR2(3) NOT NULL,
 VALOR_TOTAL NUMBER(14,2) NOT NULL,
 CONSTRAINT PK_RESUMEN_MERCADO PRIMARY KEY (ID_RESUMEN),
 CONSTRAINT FK_RM_HOGAR FOREIGN KEY (ID_HOGAR) REFERENCES HOGAR(ID_HOGAR),
 CONSTRAINT UQ_RM_HOGAR_COD UNIQUE (ID_HOGAR, CODIGO_MERCADO),
 CONSTRAINT CK_RM_COD CHECK (CODIGO_MERCADO IN ('95','96','97','98')),
 CONSTRAINT CK_RM_VAL CHECK (VALOR_TOTAL >= 0)
);

CREATE TABLE JORNADA_DIARIA (
 ID_JORNADA NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 DIA_ENCUESTA NUMBER(2,0) NOT NULL,
 FECHA DATE NOT NULL,
 TOTAL_RENGLONES NUMBER(5,0),
 OBSERVACIONES VARCHAR2(500),
 CONSTRAINT PK_JORNADA_DIARIA PRIMARY KEY (ID_JORNADA),
 CONSTRAINT FK_JD_HOGAR FOREIGN KEY (ID_HOGAR) REFERENCES HOGAR(ID_HOGAR),
 CONSTRAINT UQ_JD_HOGAR_DIA UNIQUE (ID_HOGAR, DIA_ENCUESTA),
 CONSTRAINT CK_JD_DIA CHECK (DIA_ENCUESTA BETWEEN 1 AND 14),
 CONSTRAINT CK_JD_REN CHECK (TOTAL_RENGLONES >= 0)
);

CREATE TABLE UNIDAD_MEDIDA (
 ID_UNIDAD NUMBER(5,0) NOT NULL,
 CODIGO VARCHAR2(5) NOT NULL,
