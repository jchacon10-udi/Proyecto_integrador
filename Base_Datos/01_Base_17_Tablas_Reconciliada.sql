 NOMBRE VARCHAR2(180) NOT NULL,
 CONSTRAINT PK_LUGAR_COMPRA PRIMARY KEY (ID_LUGAR),
 CONSTRAINT UQ_LC_CODIGO UNIQUE (CODIGO)
