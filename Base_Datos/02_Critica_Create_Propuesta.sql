-- Oracle 10g; aplicar sólo tras inspeccionar el esquema. DDL hace COMMIT implícito.
-- Conservar las 17 tablas originales. No usar en caso de objetos homónimos.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
 N NUMBER;
BEGIN
 SELECT COUNT(*) INTO N FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME='HOGAR' AND COLUMN_NAME='ID_HOGAR'
     OR TABLE_NAME='USUARIO' AND COLUMN_NAME='ID_USUARIO')
 AND DATA_TYPE='NUMBER' AND NVL(DATA_SCALE,0)=0;
 IF N<>2 THEN RAISE_APPLICATION_ERROR(-20001,'Inspeccionar PK numericas de HOGAR y USUARIO'); END IF;
 SELECT COUNT(*) INTO N FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC
 ON C.CONSTRAINT_NAME=CC.CONSTRAINT_NAME
 WHERE C.CONSTRAINT_TYPE IN ('P','U') AND C.STATUS='ENABLED'
 AND (C.TABLE_NAME='HOGAR' AND CC.COLUMN_NAME='ID_HOGAR'
   OR C.TABLE_NAME='USUARIO' AND CC.COLUMN_NAME='ID_USUARIO')
 AND NOT EXISTS (SELECT 1 FROM USER_CONS_COLUMNS X
                 WHERE X.CONSTRAINT_NAME=C.CONSTRAINT_NAME AND X.POSITION>1);
 IF N<2 THEN RAISE_APPLICATION_ERROR(-20002,'Faltan claves candidatas simples compatibles'); END IF;
 SELECT COUNT(*) INTO N FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('ROL','USUARIO') AND
 (COLUMN_NAME='ID_ROL' OR TABLE_NAME='ROL' AND COLUMN_NAME='NOMBRE');
 IF N<>3 THEN RAISE_APPLICATION_ERROR(-20003,'Inspeccionar contrato de roles'); END IF;
 SELECT COUNT(*) INTO N FROM USER_OBJECTS WHERE OBJECT_NAME IN
 ('REVISION_CRITICA','HALLAZGO_CRITICA','SEQ_REVISION_CRITICA',
 'SEQ_HALLAZGO_CRITICA','BI_REVISION_CRITICA','BI_HALLAZGO_CRITICA',
 'BU_HC_ESTADOS','BD_HC_HISTORIAL','BI_RC_ROL','BU_RC_HISTORIAL',
 'BD_RC_HISTORIAL','IX_RC_HOGAR','IX_RC_CRITICO','IX_HC_REVISION','IX_HC_RESPONSABLE');
 IF N<>0 THEN RAISE_APPLICATION_ERROR(-20004,'Objetos homonimos: no aplicar este create'); END IF;
END;
/
CREATE TABLE REVISION_CRITICA (
 ID_REVISION NUMBER(10,0) NOT NULL,
 ID_HOGAR NUMBER(10,0) NOT NULL,
 ID_CRITICO NUMBER(10,0) NOT NULL,
 FECHA_REVISION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 ESTADO VARCHAR2(15) DEFAULT 'EN_REVISION' NOT NULL,
 RESULTADO VARCHAR2(500),
 OBSERVACIONES VARCHAR2(500),
 CONSTRAINT PK_REVISION_CRITICA PRIMARY KEY(ID_REVISION),
 CONSTRAINT FK_RC_HOGAR FOREIGN KEY(ID_HOGAR) REFERENCES HOGAR(ID_HOGAR),
 CONSTRAINT FK_RC_USUARIO FOREIGN KEY(ID_CRITICO) REFERENCES USUARIO(ID_USUARIO),
 CONSTRAINT CK_RC_ESTADO CHECK(ESTADO IN ('EN_REVISION','OBSERVADA','CONFORME')),
 CONSTRAINT CK_RC_RESULTADO CHECK(ESTADO='EN_REVISION' OR RESULTADO IS NOT NULL)
);
CREATE TABLE HALLAZGO_CRITICA (
 ID_HALLAZGO NUMBER(10,0) NOT NULL,
 ID_REVISION NUMBER(10,0) NOT NULL,
 CAPITULO VARCHAR2(3) NOT NULL,
 DIA_ENCUESTA NUMBER(2,0),
 DESCRIPCION VARCHAR2(1000) NOT NULL,
 ESTADO VARCHAR2(15) DEFAULT 'ABIERTO' NOT NULL,
 ID_RESPONSABLE NUMBER(10,0),
 FECHA_CORRECCION TIMESTAMP,
 FECHA_VERIFICACION TIMESTAMP,
 OBSERVACION_RESPUESTA VARCHAR2(1000),
 HISTORIAL_SUBSANACION CLOB NOT NULL,
 CONSTRAINT PK_HALLAZGO_CRITICA PRIMARY KEY(ID_HALLAZGO),
 CONSTRAINT FK_HC_REVISION FOREIGN KEY(ID_REVISION) REFERENCES REVISION_CRITICA(ID_REVISION),
 CONSTRAINT FK_HC_RESPONSABLE FOREIGN KEY(ID_RESPONSABLE) REFERENCES USUARIO(ID_USUARIO),
 CONSTRAINT CK_HC_CAPITULO CHECK(CAPITULO IN ('A','B','C','D','D1','D2')),
 CONSTRAINT CK_HC_DIA CHECK(DIA_ENCUESTA BETWEEN 1 AND 14),
 CONSTRAINT CK_HC_ESTADO CHECK(ESTADO IN ('ABIERTO','CORREGIDO','VERIFICADO')),
 CONSTRAINT CK_HC_CORRECCION CHECK(ESTADO='ABIERTO' OR
  (ID_RESPONSABLE IS NOT NULL AND FECHA_CORRECCION IS NOT NULL AND OBSERVACION_RESPUESTA IS NOT NULL)),
 CONSTRAINT CK_HC_VERIFICACION CHECK(ESTADO<>'VERIFICADO' OR FECHA_VERIFICACION IS NOT NULL),
 CONSTRAINT CK_HC_FECHAS CHECK(FECHA_VERIFICACION IS NULL OR
  (FECHA_CORRECCION IS NOT NULL AND FECHA_VERIFICACION>=FECHA_CORRECCION))
);
CREATE INDEX IX_RC_HOGAR ON REVISION_CRITICA(ID_HOGAR);
CREATE INDEX IX_RC_CRITICO ON REVISION_CRITICA(ID_CRITICO);
CREATE INDEX IX_HC_REVISION ON HALLAZGO_CRITICA(ID_REVISION);
CREATE INDEX IX_HC_RESPONSABLE ON HALLAZGO_CRITICA(ID_RESPONSABLE);
CREATE SEQUENCE SEQ_REVISION_CRITICA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_HALLAZGO_CRITICA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE TRIGGER BI_REVISION_CRITICA BEFORE INSERT ON REVISION_CRITICA FOR EACH ROW
BEGIN
 IF :NEW.ID_REVISION IS NULL THEN
  SELECT SEQ_REVISION_CRITICA.NEXTVAL INTO :NEW.ID_REVISION FROM DUAL;
 END IF;
END;
/
CREATE TRIGGER BI_RC_ROL BEFORE INSERT OR UPDATE OF ID_CRITICO ON REVISION_CRITICA FOR EACH ROW
DECLARE N NUMBER;
BEGIN
 SELECT COUNT(*) INTO N FROM USUARIO U JOIN ROL R ON R.ID_ROL=U.ID_ROL
 WHERE U.ID_USUARIO=:NEW.ID_CRITICO AND R.NOMBRE='Crítico-digitador';
 IF N<>1 THEN RAISE_APPLICATION_ERROR(-20010,'El autor debe tener rol Critico-digitador'); END IF;
END;
/
CREATE TRIGGER BU_RC_HISTORIAL BEFORE UPDATE ON REVISION_CRITICA FOR EACH ROW
BEGIN
 IF :OLD.ESTADO<>'EN_REVISION' THEN
  RAISE_APPLICATION_ERROR(-20016,'Revision concluida inmutable; crear un nuevo cotejo');
 END IF;
 IF :NEW.ID_REVISION<>:OLD.ID_REVISION OR :NEW.ID_HOGAR<>:OLD.ID_HOGAR
 OR :NEW.ID_CRITICO<>:OLD.ID_CRITICO OR :NEW.FECHA_REVISION<>:OLD.FECHA_REVISION THEN
  RAISE_APPLICATION_ERROR(-20017,'Conservar identidad, autor y fecha de la revision');
 END IF;
END;
/
CREATE TRIGGER BD_RC_HISTORIAL BEFORE DELETE ON REVISION_CRITICA FOR EACH ROW
BEGIN
 RAISE_APPLICATION_ERROR(-20018,'Conservar historial de revisiones');
END;
/
CREATE TRIGGER BI_HALLAZGO_CRITICA BEFORE INSERT ON HALLAZGO_CRITICA FOR EACH ROW
BEGIN
 IF :NEW.ID_HALLAZGO IS NULL THEN
  SELECT SEQ_HALLAZGO_CRITICA.NEXTVAL INTO :NEW.ID_HALLAZGO FROM DUAL;
 END IF;
 IF :NEW.ESTADO<>'ABIERTO' THEN RAISE_APPLICATION_ERROR(-20011,'El hallazgo inicia ABIERTO'); END IF;
 :NEW.HISTORIAL_SUBSANACION := TO_CLOB('<evento estado="ABIERTO" fecha="') ||
 TO_CHAR(SYSTIMESTAMP,'YYYY-MM-DD"T"HH24:MI:SS.FF') || '" cliente="' ||
 DBMS_XMLGEN.CONVERT(NVL(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),'NO_ATRIBUIDO')) || '">' ||
 DBMS_XMLGEN.CONVERT(:NEW.DESCRIPCION) || '</evento>';
END;
/
CREATE TRIGGER BU_HC_ESTADOS BEFORE UPDATE ON HALLAZGO_CRITICA FOR EACH ROW
BEGIN
 IF :NEW.ID_HALLAZGO<>:OLD.ID_HALLAZGO OR :NEW.ID_REVISION<>:OLD.ID_REVISION
 OR :NEW.CAPITULO<>:OLD.CAPITULO OR NVL(:NEW.DIA_ENCUESTA,-1)<>NVL(:OLD.DIA_ENCUESTA,-1)
 OR :NEW.DESCRIPCION<>:OLD.DESCRIPCION THEN
  RAISE_APPLICATION_ERROR(-20012,'No sobrescribir el hallazgo original; registrar uno nuevo');
 END IF;
 IF :OLD.ESTADO='VERIFICADO' THEN RAISE_APPLICATION_ERROR(-20013,'Hallazgo verificado inmutable'); END IF;
 IF :NEW.ESTADO<>:OLD.ESTADO AND NOT
  (:OLD.ESTADO='ABIERTO' AND :NEW.ESTADO='CORREGIDO' OR
   :OLD.ESTADO='CORREGIDO' AND :NEW.ESTADO='VERIFICADO') THEN
  RAISE_APPLICATION_ERROR(-20014,'Transicion de estado no permitida');
 END IF;
 :NEW.HISTORIAL_SUBSANACION := :OLD.HISTORIAL_SUBSANACION || '<evento estado="' ||
 :NEW.ESTADO || '" fecha="' || TO_CHAR(SYSTIMESTAMP,'YYYY-MM-DD"T"HH24:MI:SS.FF') ||
 '" cliente="' || DBMS_XMLGEN.CONVERT(NVL(SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'),'NO_ATRIBUIDO')) ||
 '" responsable="' || TO_CHAR(:NEW.ID_RESPONSABLE) ||
 '" correccion="' || TO_CHAR(:NEW.FECHA_CORRECCION,'YYYY-MM-DD"T"HH24:MI:SS.FF') ||
 '" verificacion="' || TO_CHAR(:NEW.FECHA_VERIFICACION,'YYYY-MM-DD"T"HH24:MI:SS.FF') || '">' ||
 DBMS_XMLGEN.CONVERT(NVL(:NEW.OBSERVACION_RESPUESTA,'Sin respuesta')) || '</evento>';
END;
/
CREATE TRIGGER BD_HC_HISTORIAL BEFORE DELETE ON HALLAZGO_CRITICA FOR EACH ROW
BEGIN
 RAISE_APPLICATION_ERROR(-20015,'Conservar historial; no eliminar hallazgos');
END;
/
SELECT NAME,TYPE,LINE,POSITION,TEXT FROM USER_ERRORS
WHERE NAME IN ('BI_REVISION_CRITICA','BI_HALLAZGO_CRITICA','BU_HC_ESTADOS',
 'BD_HC_HISTORIAL','BI_RC_ROL','BU_RC_HISTORIAL','BD_RC_HISTORIAL');
