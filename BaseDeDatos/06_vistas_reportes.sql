SET DEFINE OFF

-- Jornada con fecha y día de la semana derivados y control de renglones.
CREATE OR REPLACE VIEW V_JORNADA AS
SELECT J.ID_HOGAR,
       H.CODIGO_OPERATIVO,
       J.DIA_ENCUESTA,
       H.FECHA_INICIO + J.DIA_ENCUESTA - 1 AS FECHA,
       TRIM(TO_CHAR(H.FECHA_INICIO + J.DIA_ENCUESTA - 1, 'Day', 'NLS_DATE_LANGUAGE=SPANISH')) AS DIA_SEMANA,
       J.TOTAL_RENGLONES AS RENGLONES_DECLARADOS,
       (SELECT COUNT(*) FROM GASTO_DIARIO G WHERE G.ID_HOGAR = J.ID_HOGAR AND G.DIA_ENCUESTA = J.DIA_ENCUESTA) AS RENGLONES_D,
       (SELECT COUNT(*) FROM COMIDA_FUERA C WHERE C.ID_HOGAR = J.ID_HOGAR AND C.DIA_ENCUESTA = J.DIA_ENCUESTA) AS RENGLONES_D1,
       J.OBSERVACIONES
  FROM JORNADA_DIARIA J
  JOIN HOGAR H ON H.ID_HOGAR = J.ID_HOGAR;

-- Reporte 1. Avance del seguimiento por hogar (CU-10).
CREATE OR REPLACE VIEW V_AVANCE_HOGAR AS
SELECT H.ID_HOGAR,
       H.CODIGO_OPERATIVO,
       H.ESTADO,
       H.FECHA_INICIO,
       H.FECHA_INICIO + 13 AS FECHA_FIN,
       (SELECT COUNT(*) FROM JORNADA_DIARIA J WHERE J.ID_HOGAR = H.ID_HOGAR AND J.TOTAL_RENGLONES IS NOT NULL) AS DIAS_DECLARADOS,
       (SELECT COUNT(*) FROM GASTO_DIARIO G WHERE G.ID_HOGAR = H.ID_HOGAR) AS RENGLONES_D,
       (SELECT COUNT(*) FROM COMIDA_FUERA C WHERE C.ID_HOGAR = H.ID_HOGAR) AS RENGLONES_D1,
       (SELECT COUNT(*) FROM CARACTERISTICA_GASTO K WHERE K.ID_HOGAR = H.ID_HOGAR) AS GRUPOS_CAPITULO_C,
       (SELECT NVL(SUM(G.VALOR_PAGADO), 0) FROM GASTO_DIARIO G WHERE G.ID_HOGAR = H.ID_HOGAR)
     + (SELECT NVL(SUM(C.VALOR_PAGADO), 0) FROM COMIDA_FUERA C WHERE C.ID_HOGAR = H.ID_HOGAR) AS VALOR_TOTAL,
       (SELECT COUNT(*) FROM HALLAZGO_CRITICA X WHERE X.ID_HOGAR = H.ID_HOGAR AND X.ESTADO = 'ABIERTO') AS HALLAZGOS_ABIERTOS
  FROM HOGAR H;

-- Reporte 2. Detalle de gastos D con nombres de catálogo y fecha derivada.
CREATE OR REPLACE VIEW V_GASTO_DETALLE AS
SELECT G.ID_HOGAR, H.CODIGO_OPERATIVO, G.DIA_ENCUESTA,
       H.FECHA_INICIO + G.DIA_ENCUESTA - 1 AS FECHA,
       G.NUMERO_ORDEN, G.DESCRIPCION, G.TIPO_ITEM, G.CANTIDAD,
       NVL(G.OTRA_UNIDAD, U.NOMBRE) AS UNIDAD, G.EQUIVALENCIA_G_CC,
       NVL(G.OTRA_FORMA, F.NOMBRE) AS FORMA_ADQUISICION,
       L.NOMBRE AS LUGAR_COMPRA, G.VALOR_PAGADO, Q.NOMBRE AS FRECUENCIA,
       DECODE(G.TIPO_GASTO, '1', 'Hogar', '2', 'Personal', 'NA', 'No aplica') AS TIPO_GASTO,
       US.NOMBRE_USUARIO AS DIGITADO_POR, G.FECHA_REGISTRO
  FROM GASTO_DIARIO G
  JOIN HOGAR H             ON H.ID_HOGAR = G.ID_HOGAR
  JOIN FORMA_ADQUISICION F ON F.COD_FORMA = G.COD_FORMA
  JOIN USUARIO US          ON US.ID_USUARIO = G.ID_USUARIO_REGISTRO
  LEFT JOIN UNIDAD_MEDIDA U     ON U.COD_UNIDAD = G.COD_UNIDAD
  LEFT JOIN LUGAR_COMPRA L      ON L.COD_LUGAR = G.COD_LUGAR
  LEFT JOIN FRECUENCIA_COMPRA Q ON Q.COD_FRECUENCIA = G.COD_FRECUENCIA;

-- Reporte 3. Gasto por forma de adquisición (compra vs. no monetario).
CREATE OR REPLACE VIEW V_GASTO_POR_FORMA AS
SELECT F.COD_FORMA, F.NOMBRE AS FORMA_ADQUISICION,
       COUNT(X.VALOR_PAGADO) AS RENGLONES,
       NVL(SUM(X.VALOR_PAGADO), 0) AS VALOR_TOTAL
  FROM FORMA_ADQUISICION F
  LEFT JOIN (SELECT COD_FORMA, VALOR_PAGADO FROM GASTO_DIARIO
             UNION ALL
             SELECT COD_FORMA, VALOR_PAGADO FROM COMIDA_FUERA) X ON X.COD_FORMA = F.COD_FORMA
 GROUP BY F.COD_FORMA, F.NOMBRE;

-- Reporte 4. Gasto por lugar de compra (solo compras).
CREATE OR REPLACE VIEW V_GASTO_POR_LUGAR AS
SELECT L.COD_LUGAR, L.NOMBRE AS LUGAR_COMPRA,
       COUNT(X.VALOR_PAGADO) AS RENGLONES,
       NVL(SUM(X.VALOR_PAGADO), 0) AS VALOR_TOTAL
  FROM LUGAR_COMPRA L
  LEFT JOIN (SELECT COD_LUGAR, VALOR_PAGADO FROM GASTO_DIARIO
             UNION ALL
             SELECT COD_LUGAR, VALOR_PAGADO FROM COMIDA_FUERA) X ON X.COD_LUGAR = L.COD_LUGAR
 GROUP BY L.COD_LUGAR, L.NOMBRE;

-- Reporte 5. Comidas fuera del hogar por tipo de comida y domicilio.
CREATE OR REPLACE VIEW V_COMIDAS_POR_TIPO AS
SELECT T.COD_TIPO_COMIDA, T.NOMBRE AS TIPO_COMIDA,
       COUNT(C.VALOR_PAGADO) AS RENGLONES,
       SUM(CASE WHEN C.A_DOMICILIO = 'S' THEN 1 ELSE 0 END) AS A_DOMICILIO,
       NVL(SUM(C.VALOR_PAGADO), 0) AS VALOR_TOTAL
  FROM TIPO_COMIDA T
  LEFT JOIN COMIDA_FUERA C ON C.COD_TIPO_COMIDA = T.COD_TIPO_COMIDA
 GROUP BY T.COD_TIPO_COMIDA, T.NOMBRE;

-- Reporte 6. Carga de trabajo por encuestador y estado de sus hogares.
CREATE OR REPLACE VIEW V_CARGA_ENCUESTADOR AS
SELECT U.ID_USUARIO, U.NOMBRE_COMPLETO AS ENCUESTADOR,
       COUNT(H.ID_HOGAR) AS HOGARES,
       SUM(CASE WHEN H.ESTADO = 'EN_CAPTURA' THEN 1 ELSE 0 END) AS EN_CAPTURA,
       SUM(CASE WHEN H.ESTADO = 'CERRADO'    THEN 1 ELSE 0 END) AS CERRADOS,
       SUM(CASE WHEN H.ESTADO = 'DEVUELTO'   THEN 1 ELSE 0 END) AS DEVUELTOS,
       SUM(CASE WHEN H.ESTADO = 'APROBADO'   THEN 1 ELSE 0 END) AS APROBADOS
  FROM USUARIO U
  JOIN ROL R ON R.ID_ROL = U.ID_ROL AND R.NOMBRE = 'ENCUESTADOR'
  LEFT JOIN ASIGNACION_HOGAR A ON A.ID_USUARIO = U.ID_USUARIO AND A.ESTADO = 'VIGENTE'
  LEFT JOIN HOGAR H ON H.ID_HOGAR = A.ID_HOGAR
 GROUP BY U.ID_USUARIO, U.NOMBRE_COMPLETO;

-- Reporte 7. Hallazgos de crítica con su último evento (CU-12 a CU-14).
CREATE OR REPLACE VIEW V_HALLAZGOS AS
SELECT X.ID_HOGAR, H.CODIGO_OPERATIVO, X.NUMERO_REVISION, X.NUMERO_HALLAZGO,
       X.CAPITULO, X.DIA_ENCUESTA, X.DESCRIPCION, X.ESTADO,
       C.NOMBRE_USUARIO AS CRITICO, X.FECHA_REGISTRO,
       R.NOMBRE_USUARIO AS RESPONSABLE, X.FECHA_CORRECCION, X.FECHA_VERIFICACION,
       (SELECT COUNT(*) FROM EVENTO_HALLAZGO E
         WHERE E.ID_HOGAR = X.ID_HOGAR AND E.NUMERO_REVISION = X.NUMERO_REVISION
           AND E.NUMERO_HALLAZGO = X.NUMERO_HALLAZGO) AS EVENTOS
  FROM HALLAZGO_CRITICA X
  JOIN HOGAR H            ON H.ID_HOGAR = X.ID_HOGAR
  JOIN REVISION_CRITICA V ON V.ID_HOGAR = X.ID_HOGAR AND V.NUMERO_REVISION = X.NUMERO_REVISION
  JOIN USUARIO C          ON C.ID_USUARIO = V.ID_CRITICO
  LEFT JOIN USUARIO R     ON R.ID_USUARIO = X.ID_RESPONSABLE;

-- Reporte 8. Características del gasto (capítulo C) por hogar.
CREATE OR REPLACE VIEW V_CARACTERISTICAS_C AS
SELECT K.ID_HOGAR, H.CODIGO_OPERATIVO, K.COD_GRUPO, G.NOMBRE AS GRUPO_ALIMENTO,
       Q.NOMBRE AS FRECUENCIA, K.VALOR_ULTIMA_COMPRA, K.COMPRARA_14_DIAS
  FROM CARACTERISTICA_GASTO K
  JOIN HOGAR H             ON H.ID_HOGAR = K.ID_HOGAR
  JOIN GRUPO_ALIMENTO G    ON G.COD_GRUPO = K.COD_GRUPO
  JOIN FRECUENCIA_COMPRA Q ON Q.COD_FRECUENCIA = K.COD_FRECUENCIA;
