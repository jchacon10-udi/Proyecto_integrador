PROMPT === R01. Reporte: avance por hogar
COLUMN CODIGO_OPERATIVO FORMAT A16
SELECT CODIGO_OPERATIVO, ESTADO, FECHA_INICIO, FECHA_FIN, DIAS_DECLARADOS,
       RENGLONES_D, RENGLONES_D1, GRUPOS_CAPITULO_C, VALOR_TOTAL, HALLAZGOS_ABIERTOS
  FROM V_AVANCE_HOGAR ORDER BY CODIGO_OPERATIVO;

PROMPT === R02. Reporte: día 6 del hogar 1 (ejemplo oficial del cuadernillo)
COLUMN DESCRIPCION FORMAT A24
COLUMN UNIDAD FORMAT A14
COLUMN FORMA_ADQUISICION FORMAT A20
COLUMN LUGAR_COMPRA FORMAT A24
COLUMN FRECUENCIA FORMAT A14
SELECT NUMERO_ORDEN, DESCRIPCION, CANTIDAD, UNIDAD, FORMA_ADQUISICION,
       SUBSTR(LUGAR_COMPRA, 1, 24) LUGAR_COMPRA, VALOR_PAGADO, FRECUENCIA, TIPO_GASTO
  FROM V_GASTO_DETALLE
 WHERE CODIGO_OPERATIVO = 'ENPH-11001-0001' AND DIA_ENCUESTA = 6
 ORDER BY NUMERO_ORDEN;

