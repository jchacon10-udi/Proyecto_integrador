-- =====================================================================
-- ENPH - 10. Verificación del montaje (consultas de metadatos)
-- Evidencia de que los objetos existen, compilan y tienen datos.
-- =====================================================================
SET LINESIZE 200
SET PAGESIZE 100
COLUMN OBJECT_TYPE FORMAT A12
COLUMN OBJECT_NAME FORMAT A28
COLUMN TABLE_NAME FORMAT A22
COLUMN STATUS FORMAT A8

PROMPT === V01. Versión del motor
SELECT BANNER FROM V$VERSION WHERE ROWNUM = 1;

PROMPT === V02. Objetos por tipo y estado (esperado: 23 TABLE, 2 SEQUENCE, 11 TRIGGER, 8 FUNCTION, 14 PROCEDURE, 9 VIEW; todos VALID)
SELECT OBJECT_TYPE, STATUS, COUNT(*) AS TOTAL
  FROM USER_OBJECTS
 WHERE OBJECT_TYPE IN ('TABLE','SEQUENCE','TRIGGER','FUNCTION','PROCEDURE','VIEW')
 GROUP BY OBJECT_TYPE, STATUS
 ORDER BY OBJECT_TYPE;

PROMPT === V03. Objetos inválidos (esperado: ninguna fila)
SELECT OBJECT_TYPE, OBJECT_NAME FROM USER_OBJECTS WHERE STATUS <> 'VALID';

PROMPT === V04. Errores de compilación (esperado: ninguna fila)
SELECT NAME, TYPE, LINE, TEXT FROM USER_ERRORS ORDER BY NAME, SEQUENCE;

PROMPT === V05. Restricciones por tipo (P=PK, R=FK, U=UNIQUE, C=CHECK incluye NOT NULL)
SELECT CONSTRAINT_TYPE, COUNT(*) AS TOTAL FROM USER_CONSTRAINTS
 WHERE TABLE_NAME NOT LIKE 'BIN$%' GROUP BY CONSTRAINT_TYPE ORDER BY CONSTRAINT_TYPE;

PROMPT === V06. Restricciones deshabilitadas (esperado: ninguna fila)
SELECT TABLE_NAME, CONSTRAINT_NAME FROM USER_CONSTRAINTS WHERE STATUS <> 'ENABLED';

