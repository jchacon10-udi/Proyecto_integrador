-- =====================================================================
-- ENPH - 07. Roles de base de datos y privilegios (Oracle 10g)
-- Ejecutar como ENPH después de crear tablas, programas y vistas.
-- Principio de mínimo privilegio: los actores escriben SOLO mediante
-- procedimientos; las tablas transaccionales no se exponen para DML directo.
-- Requiere el privilegio CREATE ROLE (00_crear_esquema_DBA.sql lo otorga).
-- =====================================================================
SET DEFINE OFF

-- Crea los roles si no existen (Oracle 10g no tiene CREATE ROLE IF NOT EXISTS).
DECLARE
  PROCEDURE crear(p VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE 'CREATE ROLE ' || p;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE <> -1921 THEN RAISE; END IF;  -- ORA-01921: el rol ya existe
  END;
BEGIN
  crear('ENPH_ROL_CONSULTA');
  crear('ENPH_ROL_INFORMANTE');
  crear('ENPH_ROL_ENCUESTADOR');
  crear('ENPH_ROL_SUPERVISOR');
  crear('ENPH_ROL_CRITICO');
  crear('ENPH_ROL_APLICACION');
END;
/

-- Consulta común: catálogos, vistas y funciones de cálculo
BEGIN
  FOR t IN (SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME IN
            ('ROL','RESULTADO_ENTREVISTA','GRUPO_ALIMENTO','FRECUENCIA_COMPRA','TIPO_MERCADO',
             'UNIDAD_MEDIDA','FORMA_ADQUISICION','LUGAR_COMPRA','TIPO_COMIDA','FORMA_PAGO')) LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON ' || t.TABLE_NAME || ' TO ENPH_ROL_CONSULTA';
  END LOOP;
  FOR v IN (SELECT VIEW_NAME FROM USER_VIEWS WHERE VIEW_NAME LIKE 'V\_%' ESCAPE '\') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON ' || v.VIEW_NAME || ' TO ENPH_ROL_CONSULTA';
  END LOOP;
  FOR f IN (SELECT OBJECT_NAME FROM USER_OBJECTS WHERE OBJECT_TYPE = 'FUNCTION'
             AND OBJECT_NAME IN ('FN_FECHA_DIA','FN_DIA_DE_FECHA','FN_RENGLONES_DIA','FN_TOTAL_GASTO',
                                 'FN_DIAS_COMPLETOS','FN_HALLAZGOS_ABIERTOS')) LOOP
    EXECUTE IMMEDIATE 'GRANT EXECUTE ON ' || f.OBJECT_NAME || ' TO ENPH_ROL_CONSULTA';
  END LOOP;
END;
/

