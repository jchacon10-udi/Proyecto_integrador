-- Asignación de roles a los usuarios de base de datos (si existen)
DECLARE
  PROCEDURE otorgar(p_rol VARCHAR2, p_usuario VARCHAR2) IS
    v_n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_n FROM ALL_USERS WHERE USERNAME = p_usuario;
    IF v_n = 1 THEN
      EXECUTE IMMEDIATE 'GRANT ' || p_rol || ' TO ' || p_usuario;
    ELSE
      DBMS_OUTPUT.PUT_LINE('Omitido: no existe el usuario ' || p_usuario);
    END IF;
  END;
BEGIN
  otorgar('ENPH_ROL_INFORMANTE',  'ENPH_INFORMANTE');
  otorgar('ENPH_ROL_ENCUESTADOR', 'ENPH_ENCUESTADOR');
  otorgar('ENPH_ROL_SUPERVISOR',  'ENPH_SUPERVISOR');
  otorgar('ENPH_ROL_CRITICO',     'ENPH_CRITICO');
  otorgar('ENPH_ROL_APLICACION',  'ENPH_APP');
END;
